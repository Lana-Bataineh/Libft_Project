#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	src_len;
	size_t	i;
	char	*dup ;

	src_len = ft_strlen(s);
	dup = (char *) malloc((src_len +1) * sizeof(char));
	if (dup == NULL)
		return (NULL);
	i = 0;
	while (s[i])
	{
		dup[i] = s[i];
		i++;
	}
	dup[i] = '\0';
	return (dup);
}
